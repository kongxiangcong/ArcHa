"""Frozen toy domain: exact integer GEMV and scalar-transfer cost, not PPA."""
from __future__ import annotations

import argparse
import ast
import hashlib
import json
import math
from pathlib import Path
from typing import Any

SHAPES = [(1, 1), (5, 7), (17, 13), (32, 64)]
CONTRACT: dict[str, Any] = {
    "schema": "opc.demo.gemv.v1",
    "shapes": SHAPES,
    "seed": 19,
    "integer_semantics": "Python exact signed integers; no hardware overflow model",
    "accumulator_slots": 12,
    "metric": "scalar_transfers = weight_reads + input_reads + output_writes",
    "memory_model": "No cache; each row tile retains one x scalar and tile accumulators",
    "selection": "correctness and resource gates, then strictly fewer scalar_transfers",
    "claim_scope": "These four workloads and this analytical memory model only",
}


def canonical(value: Any) -> bytes:
    return json.dumps(value, sort_keys=True, ensure_ascii=False, separators=(",", ":")).encode()


def digest(value: Any) -> str:
    return hashlib.sha256(canonical(value)).hexdigest()


def write_json(path: Path, value: Any) -> None:
    path.write_bytes(json.dumps(value, indent=2, ensure_ascii=False).encode())


def design(tile: int, broken_tail: bool = False) -> str:
    bound = "(rows // TILE) * TILE" if broken_tail else "rows"
    return f'''# Generated by the offline template designer, not an LLM.
TILE = {tile}

def kernel(rows, cols, load_w, load_x):
    out = [0] * rows
    for start in range(0, {bound}, TILE):
        stop = min(start + TILE, rows)
        accum = [0] * (stop - start)
        for k in range(cols):
            value = load_x(k)
            for i in range(start, stop):
                accum[i - start] += load_w(i, k) * value
        for i in range(start, stop):
            out[i] = accum[i - start]
    return out
'''


def matrix(rows: int, cols: int) -> tuple[list[list[int]], list[int]]:
    # Closed-form deterministic input, including negative and zero entries.
    return ([[((i * 13 + k * 7 + 19) % 23) - 11 for k in range(cols)]
             for i in range(rows)], [((k * 5 + 19) % 17) - 8 for k in range(cols)])


def standards(source: str) -> dict[str, Any]:
    """A tiny style/scope check; explicitly not a sandbox or complete code review."""
    tree = ast.parse(source)
    forbidden = (ast.Import, ast.ImportFrom, ast.Global, ast.Nonlocal, ast.With,
                 ast.AsyncWith, ast.While, ast.Try, ast.Raise, ast.Attribute)
    calls = {"range", "min", "load_w", "load_x"}
    problems = []
    for node in ast.walk(tree):
        if isinstance(node, forbidden):
            problems.append(type(node).__name__)
        if isinstance(node, ast.Call) and not (
            isinstance(node.func, ast.Name) and node.func.id in calls
        ):
            problems.append("unapproved call")
    return {"verdict": "pass" if not problems else "fail", "findings": problems,
            "scope": "AST restricted operations only; not human/LLM maintainability review"}


def validate_tile(source: str, planned_tile: int) -> list[str]:
    """Bind the template's sole TILE constant to the frozen plan, fail closed."""
    tree = ast.parse(source)
    assignments = [node for node in tree.body if isinstance(node, ast.Assign)
                   and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name)
                   and node.targets[0].id == "TILE"]
    stores = [node for node in ast.walk(tree) if isinstance(node, ast.Name)
              and node.id == "TILE" and isinstance(node.ctx, ast.Store)]
    shadowed = any((isinstance(node, ast.arg) and node.arg == "TILE") or
                   (isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef))
                    and node.name == "TILE") for node in ast.walk(tree))
    if len(assignments) != 1 or len(stores) != 1 or shadowed:
        return ["TILE must have exactly one unshadowed top-level constant declaration"]
    value = assignments[0].value
    if not isinstance(value, ast.Constant) or type(value.value) is not int or value.value <= 0:
        return ["TILE must be a positive integer literal"]
    if type(planned_tile) is not int or planned_tile <= 0 or value.value != planned_tile:
        return ["candidate TILE does not match frozen plan tile"]
    return []


def execute(candidate: Path, tile: int, review: bool) -> dict[str, Any]:
    source = candidate.read_text(encoding="utf-8")
    code_review = standards(source)
    if code_review["verdict"] != "pass":
        return {"standards": code_review, "spec": {"verdict": "fail", "findings": ["code gate"]}}
    tile_findings = validate_tile(source, tile)
    if tile_findings:
        return {"standards": code_review, "spec": {"verdict": "fail", "findings": tile_findings}}
    namespace: dict[str, Any] = {}
    # A common namespace makes module-level TILE visible to kernel.
    namespace["__builtins__"] = {"range": range, "min": min}
    # Intentional execution of the local template candidate; not a security sandbox.
    exec(compile(source, str(candidate), "exec"), namespace)  # noqa: S102
    results = []
    findings = []
    for rows, cols in SHAPES:
        weights, inputs = matrix(rows, cols)
        counts = {"weight_reads": 0, "input_reads": 0, "output_writes": rows}

        def load_w(i: int, k: int, counts: dict[str, int] = counts,
                   weights: list[list[int]] = weights) -> int:
            counts["weight_reads"] += 1
            return weights[i][k]

        def load_x(k: int, counts: dict[str, int] = counts, inputs: list[int] = inputs) -> int:
            counts["input_reads"] += 1
            return inputs[k]

        output = namespace["kernel"](rows, cols, load_w, load_x)
        # Reference has no tiling and never imports candidate output or metrics.
        golden = [sum(w * x for w, x in zip(row, inputs, strict=True)) for row in weights]
        correct = output == golden
        if not correct:
            findings.append(f"functional mismatch {rows}x{cols}")
        if review:
            expected = {"weight_reads": rows * cols,
                        "input_reads": math.ceil(rows / tile) * cols, "output_writes": rows}
            if counts != expected:
                findings.append(f"trace/model mismatch {rows}x{cols}")
        results.append({"shape": [rows, cols], "correct": correct, "output": output,
                        "golden": golden if review else None, **counts,
                        "scalar_transfers": sum(counts.values())})
    if tile > CONTRACT["accumulator_slots"]:
        findings.append("accumulator resource limit exceeded")
    return {"standards": code_review,
            "spec": {"verdict": "pass" if not findings else "fail", "findings": findings},
            "metrics": {"scalar_transfers": sum(r["scalar_transfers"] for r in results)},
            "cases": results, "evidence_level": "exact integer simulation + analytical memory model"}


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("candidate", type=Path)
    parser.add_argument("--tile", type=int, required=True)
    parser.add_argument("--review", action="store_true")
    args = parser.parse_args()
    print(json.dumps(execute(args.candidate, args.tile, args.review)))


if __name__ == "__main__":
    main()
